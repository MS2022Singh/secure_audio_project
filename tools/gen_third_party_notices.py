"""Regenerate THIRD_PARTY_NOTICES.md from the Rust dependency graph (Windows target)
and backend/requirements.txt. Run from the repository root:  python tools/gen_third_party_notices.py"""
import json
import subprocess

CRATES = ["src-tauri", "diviora-sync", "diviora-dsp", "diviora-client"]
packages = {}
for d in CRATES:
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"],
                         cwd=d, capture_output=True, text=True, check=True)
    for p in json.loads(out.stdout)["packages"]:
        if p["source"] is None:  # our own crates
            continue
        packages[(p["name"], p["version"])] = (p.get("license") or "see package", p.get("repository") or "")

lines = [
    "# Third-party notices",
    "",
    "Diviora Psychoacoustics includes the open-source components listed below. Each is used",
    "under its own licence (shown). No component is under the GPL or another licence that",
    "would require Diviora's own source code to be published. MPL-2.0 components are used",
    "unmodified; their source is available at the linked repositories.",
    "",
    "Generated by `tools/gen_third_party_notices.py`; regenerate after changing dependencies.",
    "",
    "## Windows audio engine and desktop app (Rust)",
    "",
    "| Component | Version | Licence | Source |",
    "|---|---|---|---|",
]
for (name, ver), (lic, repo) in sorted(packages.items()):
    lines.append(f"| {name} | {ver} | {lic} | {repo} |")
lines += [
    "",
    "## Licence server (Python, backend/)",
    "",
    "| Component | Licence |",
    "|---|---|",
    "| FastAPI | MIT |",
    "| Uvicorn | BSD-3-Clause |",
    "| cryptography | Apache-2.0 OR BSD-3-Clause |",
    "| Pydantic | MIT |",
    "",
    "## Build tools (not shipped)",
    "",
    "Tauri CLI (MIT OR Apache-2.0), NSIS (zlib/libpng), Microsoft Visual C++ build tools and",
    "Windows SDK (Microsoft licence terms; the shipped DLL is statically linked against the",
    "MSVC runtime as permitted by the Visual Studio licence).",
    "",
]
open("THIRD_PARTY_NOTICES.md", "w", encoding="utf-8").write("\n".join(lines))
print(f"{len(packages)} components written to THIRD_PARTY_NOTICES.md")
